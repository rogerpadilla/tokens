import { readFileSync, writeFileSync } from 'node:fs';
import path from 'node:path';

/** The Primer roles the sites read, by Primer's own names, so primer.style documents every one. Colours only: `light-dark()` takes nothing else. */
export const ROLES = [
  'bgColor-default',
  'bgColor-muted',
  'bgColor-inset',
  'bgColor-emphasis',
  'bgColor-neutral-muted',
  'overlay-bgColor',
  'overlay-backdrop-bgColor',
  'control-bgColor-rest',
  'control-bgColor-hover',
  'control-transparent-bgColor-hover',
  'borderColor-default',
  'borderColor-muted',
  'borderColor-emphasis',
  'focus-outlineColor',
  'fgColor-default',
  'fgColor-muted',
  'fgColor-disabled',
  'fgColor-onEmphasis',
  'fgColor-accent',
  'bgColor-accent-emphasis',
  'bgColor-accent-muted',
  ...['success', 'attention', 'danger', 'done'].flatMap((tone) => [`fgColor-${tone}`, `bgColor-${tone}-muted`, `bgColor-${tone}-emphasis`]),
  'underlineNav-borderColor-active',
];

export type Theme = Map<string, string>;

/** A theme file's first block: the explicit-mode selector, before the `prefers-color-scheme` copy of it. */
export function parseTheme(css: string): Theme {
  const block = css.replace(/\/\*[\s\S]*?\*\//g, '').match(/\{([^{}]*)\}/)?.[1] ?? '';
  return new Map([...block.matchAll(/--([\w-]+):\s*([^;]+);/g)].map(([, name, value]) => [name, value.trim()]));
}

export function resolve(name: string, theme: Theme): string {
  const value = theme.get(name);
  if (value === undefined) {
    throw new Error(`Primer defines no --${name}`);
  }
  const reference = value.match(/^var\(--([\w-]+)\)$/)?.[1];
  if (reference) {
    return resolve(reference, theme);
  }
  if (!/^#[0-9a-f]{6}([0-9a-f]{2})?$/i.test(value)) {
    throw new Error(`--${name} is not a colour: ${value}`);
  }
  return value;
}

/** What Primer leaves to a site, derived from its roles, so a site or palette restating them retints these too. */
const DERIVED = {
  'bgColor-accent-emphasis-hover': 'color-mix(in srgb, var(--bgColor-accent-emphasis), #000 14%)',
  'bgColor-accent-muted-hover': 'color-mix(in srgb, var(--fgColor-accent) 26%, transparent)',
  'fgColor-accent-hover': 'color-mix(in oklab, var(--fgColor-accent), var(--fgColor-default) 35%)',
};

const HEADER = '/* Generated by scripts/build.ts from @primer/primitives (MIT, GitHub): do not edit. */\n';

export type Files = Record<'primer.css' | 'primer.js' | 'primer.d.ts', string>;

/** The roles as CSS for the sites, and resolved for their scripts (an email, a social card, a `theme-color`). */
export function build(roles: readonly string[], light: Theme, dark: Theme): Files {
  const pairs = roles.map((role) => [role, resolve(role, light), resolve(role, dark)] as const);
  const css = pairs.map(([role, l, d]) => `  --${role}: ${l === d ? l : `light-dark(${l}, ${d})`};\n`).join('');
  // A subtree's `data-theme` (a theme preview) restates roles there, so the derivation is redone there too.
  const derived = Object.entries(DERIVED).map(([name, value]) => `  --${name}: ${value};\n`).join('');
  return {
    'primer.css': `${HEADER}:root {\n${css}}\n\n:root,\n[data-theme] {\n${derived}}\n`,
    'primer.js': `${HEADER}export const primer = {\n${pairs.map(([role, l, d]) => `  '${role}': { light: '${l}', dark: '${d}' },\n`).join('')}};\n`,
    'primer.d.ts': `${HEADER}export declare const primer: {\n${pairs.map(([role, l, d]) => `  readonly '${role}': { readonly light: '${l}'; readonly dark: '${d}' };\n`).join('')}};\n`,
  };
}

if (import.meta.main) {
  const themes = path.join(import.meta.dirname, '../node_modules/@primer/primitives/dist/css/functional/themes');
  const read = (name: string) => parseTheme(readFileSync(path.join(themes, `${name}.css`), 'utf8'));
  const stale = Object.entries(build(ROLES, read('light'), read('dark'))).filter(([file, content]) => {
    const out = path.join(import.meta.dirname, '..', file);
    if (!process.argv.includes('--check')) {
      writeFileSync(out, content);
      return false;
    }
    return readFileSync(out, 'utf8') !== content;
  });
  if (stale.length) {
    console.error(`${stale.map(([file]) => file).join(', ')} stale: run \`bun run build\`.`);
    process.exit(1);
  }
}
