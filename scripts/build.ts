import { readFileSync, writeFileSync } from 'node:fs';
import path from 'node:path';

/** The Primer roles the sites read, by Primer's own names, so primer.style documents every one. Colours only: `light-dark()` takes nothing else. */
export const ROLES = [
  'bgColor-default',
  'bgColor-muted',
  'bgColor-inset',
  'bgColor-emphasis',
  'bgColor-neutral-muted',
  'overlay-bgColor',
  'overlay-backdrop-bgColor',
  'control-bgColor-rest',
  'control-bgColor-hover',
  'control-transparent-bgColor-hover',
  'borderColor-default',
  'borderColor-muted',
  'borderColor-emphasis',
  'focus-outlineColor',
  'fgColor-default',
  'fgColor-muted',
  'fgColor-onEmphasis',
  'fgColor-accent',
  'bgColor-accent-emphasis',
  'bgColor-accent-muted',
  ...['success', 'attention', 'danger', 'done'].flatMap((tone) => [`fgColor-${tone}`, `bgColor-${tone}-muted`, `bgColor-${tone}-emphasis`]),
  'underlineNav-borderColor-active',
];

export type Theme = Map<string, string>;

/** A theme file's first block: the explicit-mode selector, before the `prefers-color-scheme` copy of it. */
export function parseTheme(css: string): Theme {
  const block = css.replace(/\/\*[\s\S]*?\*\//g, '').match(/\{([^{}]*)\}/)?.[1] ?? '';
  return new Map([...block.matchAll(/--([\w-]+):\s*([^;]+);/g)].map(([, name, value]) => [name, value.trim()]));
}

export function resolve(name: string, theme: Theme): string {
  const value = theme.get(name);
  if (value === undefined) {
    throw new Error(`Primer defines no --${name}`);
  }
  const reference = value.match(/^var\(--([\w-]+)\)$/)?.[1];
  if (reference) {
    return resolve(reference, theme);
  }
  if (!/^#[0-9a-f]{6}([0-9a-f]{2})?$/i.test(value)) {
    throw new Error(`--${name} is not a colour: ${value}`);
  }
  return value;
}

export function render(roles: readonly string[], light: Theme, dark: Theme): string {
  const lines = roles.map((role) => {
    const [l, d] = [resolve(role, light), resolve(role, dark)];
    return `  --${role}: ${l === d ? l : `light-dark(${l}, ${d})`};\n`;
  });
  return `/* Generated by scripts/build.ts from @primer/primitives (MIT, GitHub): do not edit. */\n:root {\n${lines.join('')}}\n`;
}

if (import.meta.main) {
  const themes = path.join(import.meta.dirname, '../node_modules/@primer/primitives/dist/css/functional/themes');
  const read = (name: string) => parseTheme(readFileSync(path.join(themes, `${name}.css`), 'utf8'));
  const css = render(ROLES, read('light'), read('dark'));
  const out = path.join(import.meta.dirname, '../primer.css');
  if (!process.argv.includes('--check')) {
    writeFileSync(out, css);
  } else if (readFileSync(out, 'utf8') !== css) {
    console.error('primer.css is stale: run `bun run build`.');
    process.exit(1);
  }
}
