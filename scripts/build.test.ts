import { describe, expect, it } from 'bun:test';

import { build, buildScale, parseTheme, resolve } from './build.ts';

const LIGHT = `/** header */
[data-color-mode="light"] {
  --bgColor-default: #ffffff; /** The page. */
  --bgColor-muted: #f6f8fa;
  --bgColor-inset: var(--bgColor-muted);
  --fgColor-default: #1f2328;
}
@media (prefers-color-scheme: dark) {
  [data-color-mode="auto"] {
    --bgColor-default: #0d1117;
  }
}`;

const DARK = `[data-color-mode="dark"] {
  --bgColor-default: #ffffff;
  --bgColor-muted: #151b23;
  --bgColor-inset: #010409;
  --fgColor-default: #f0f6fc;
}`;

describe('buildScale', () => {
  const css = ':root {\n  --duration-fast: 150ms;\n  --duration-base: 250ms;\n  --duration-slow: 400ms;\n}\n@media (prefers-reduced-motion: reduce) {\n  :root { --duration-fast: 0.01ms; }\n}';

  it("gives scripts the duration scale in milliseconds, from scale.css's first block", () => {
    expect(buildScale(css)['scale.js']).toContain('export const duration = { fast: 150, base: 250, slow: 400 };\n');
    expect(buildScale(css)['scale.d.ts']).toContain('export declare const duration: { readonly fast: 150; readonly base: 250; readonly slow: 400 };\n');
  });
});

describe('parseTheme', () => {
  it('reads the first block only, without comments', () => {
    expect(parseTheme(LIGHT)).toEqual(
      new Map([
        ['bgColor-default', '#ffffff'],
        ['bgColor-muted', '#f6f8fa'],
        ['bgColor-inset', 'var(--bgColor-muted)'],
        ['fgColor-default', '#1f2328'],
      ]),
    );
  });
});

describe('resolve', () => {
  it('follows a reference to the value it names', () => {
    expect(resolve('bgColor-inset', parseTheme(LIGHT))).toBe('#f6f8fa');
  });

  it('fails on a role the theme does not define', () => {
    expect(() => resolve('bgColor-missing', parseTheme(LIGHT))).toThrow('bgColor-missing');
  });

  it('fails on a value that is not a colour, which light-dark() cannot take', () => {
    const theme = new Map([['shadow-small', '0 1px 1px 0 #1f23280a']]);
    expect(() => resolve('shadow-small', theme)).toThrow('shadow-small');
  });
});

describe('build', () => {
  const files = build(['bgColor-inset', 'bgColor-default'], parseTheme(LIGHT), parseTheme(DARK));

  it('pairs each role across the two themes in CSS, and states a role equal in both once', () => {
    expect(files['primer.css']).toStartWith('/* Generated by scripts/build.ts');
    expect(files['primer.css']).toContain('  --bgColor-inset: light-dark(#f6f8fa, #010409);\n');
    expect(files['primer.css']).toContain('  --bgColor-default: #ffffff;\n');
  });

  it('derives the hovers from the roles on every element that can restate them', () => {
    expect(files['primer.css']).toContain(':root,\n[data-theme] {\n  --bgColor-accent-emphasis-hover: color-mix(');
  });

  it.each(['accent', 'danger', 'success', 'attention'])('derives a fill hover and a tint hover for the %s family', (family) => {
    expect(files['primer.css']).toContain(`  --bgColor-${family}-emphasis-hover: color-mix(in srgb, var(--bgColor-${family}-emphasis), #000 14%);\n`);
    expect(files['primer.css']).toContain(`  --bgColor-${family}-muted-hover: color-mix(in srgb, var(--fgColor-${family}) 26%, transparent);\n`);
  });

  it('gives scripts the same values, resolved, with their literal types', () => {
    expect(files['primer.js']).toContain(`  'bgColor-inset': { light: '#f6f8fa', dark: '#010409' },\n`);
    expect(files['primer.d.ts']).toContain(`  readonly 'bgColor-inset': { readonly light: '#f6f8fa'; readonly dark: '#010409' };\n`);
  });
});
